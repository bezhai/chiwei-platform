"""通信机制：参与者之间通过具名收件箱交流。

参与者之间唯一的连接。发送方只知道接收方的名字，不知道它的实现、所在的进程和
在线与否；这也是它不用 dataflow 连线的原因——连线在启动时就接好了，发送方其实知道
接收方是谁。它也不用表来传消息。

三种操作（:mod:`app.messaging.sending`）：

* ``send`` —— 发给某个具名参与者；
* ``ask`` —— 向某个具名参与者提问，同步拿到回答或"没有回答"；
* ``send_at`` —— 指定一个时刻再送达，可以发给自己。

收件箱由拥有者开设（:func:`app.messaging.receiving.inbox`），开设之后拥有者不在线时
消息一直保留、不过期。问题走收件箱旁边自己的队列，不排在拥有者正在处理的普通消息后面。
发往没开设的收件箱不投递、照样记录、告诉发送方没有送达。投递
至少一次，接收方按消息 id 去重；处理失败有限次重试后进本泳道的死信队列，可查看、可
重放（:mod:`app.messaging.dead_letters`）。每一条消息都经过记录者
（:mod:`app.messaging.record`）：交给 broker 之前先记一行，记录失败这次发送就算失败；
失败时带回消息 id，沿用它重试不会让接收方处理两遍。一切按进程的部署泳道完全隔离，
不退回 prod。

这是基础层：任何 App 都可以用，它自己不 import 任何 App 的代码。
"""
